import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

const read = path => readFileSync(new URL(`../${path}`, import.meta.url), 'utf8');
const router = read('LumaLex/App/AppRouter.swift');
const profile = read('LumaLex/Views/Profile/ProfileView.swift');
assert.doesNotMatch(router + profile, /AssessmentView|showingAssessment|Retake Vocabulary Check/);
assert.match(router, /var body: some View\s*\{\s*mainTabs/);
assert.match(router, /VocabularyView\(\)/);
assert.match(profile, /KnownExpressionsView\(\)/);
assert.match(read('LumaLex/Info.plist'), /<key>UILaunchScreen<\/key>\s*<dict\s*\/>/);
const project = read('project.yml');
assert.match(project, /- Views\/Assessment\/\*\*/);
assert.match(project, /- Services\/Assessment\/\*\*/);
assert.match(project, /UILaunchScreen:\s*\{\}/);
assert.match(project, /NSExtensionPointIdentifier: com\.apple\.widgetkit-extension/);
assert.match(project, /UIBackgroundModes: \[audio\]/);
assert.match(project, /NSSpeechRecognitionUsageDescription:/);
assert.match(project, /ASSETCATALOG_COMPILER_APPICON_NAME: AppIcon/);
const icon = JSON.parse(read('LumaLex/Assets.xcassets/AppIcon.appiconset/Contents.json'));
assert.equal(icon.images[0].size, '1024x1024');
const iconPNG = readFileSync(new URL('../LumaLex/Assets.xcassets/AppIcon.appiconset/AppIcon.png', import.meta.url));
assert.equal(iconPNG.subarray(1, 4).toString(), 'PNG');
assert.equal(iconPNG.readUInt32BE(16), 1024);
assert.equal(iconPNG.readUInt32BE(20), 1024);
assert.equal(iconPNG[25], 2, 'App icon must be opaque RGB, without alpha');
const player = read('LumaLex/Views/Player/PlayerView.swift');
assert.match(player, /if let savedSegments \{ return savedSegments \}/);
assert.match(player, /try modelContext\.save\(\)\s*savedSegments = inserted\.sorted/);
assert.match(player, /player\.setSubtitles\(savedSegments \?\? \[\]\)/);
assert.match(player, /try saveTranscript\(parsed, source: "imported"\)\s*mode = \.bilingual/);
assert.match(player, /case \.failure\(let error\):/);
assert.doesNotMatch(player, /sheet\(item: \$selectedWord/);
assert.match(player, /originalSentence: segment\.english/);
assert.match(player, /dictionarySource = entry == nil/);
const row = read('LumaLex/Views/Player/SubtitleRow.swift');
const review = read('LumaLex/Views/Vocabulary/ReviewView.swift');
assert.match(review, /ScrollView/);
assert.match(review, /safeAreaInset\(edge: \.bottom\)/);
const live = read('LumaLex/LiveActivity/LiveActivityCoordinator.swift');
assert.doesNotMatch(live, /timeIntervalSince\(lastUpdate\) >= 15/);
assert.match(live, /chinese != lastChinese/);
assert.match(row, /onTapGesture\(count: 2\)/);
assert.match(row, /savedLemmas\.contains\(OfflineDictionary\.shared\.lemma/);
assert.match(read('LumaLex/Views/Player/MiniPlayerView.swift'), /ProgressView/);
const entries = JSON.parse(read('LumaLex/Resources/OfflineDictionary.json'));
assert.ok(entries.length >= 40000);
assert.ok(entries.some(entry => entry.word === 'house' && entry.translation));
console.log('Assessment removal and launch screen configuration checks passed.');
